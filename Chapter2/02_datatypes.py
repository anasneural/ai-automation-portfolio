# A data type tells us what kind of value a variable stores, such as text (str), whole numbers (int), decimal numbers (float), or True/False (bool).
# Examples
age = 25 #age is a integer datatype
name = "anas" #name is a sting datatype
value = 24.5 #value is a floating number because .5 is a decimal number
c = False # C is a boolean datatype
d = None # d is a none datatype